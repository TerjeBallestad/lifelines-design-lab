#!/usr/bin/env node
// SB-110: sync the activity catalog from core-loop into a generated module.
// The engine's scripts/tools/export_activity_catalog.gd reflects ActivityIds
// and dumps JSON; this script runs it headless and rewrites
// src/content/generated/activityCatalog.ts. The module is committed, so
// consumers (compiler, visit editor picker) never need Godot.
//
//   npm run gen:activities          regenerate the module
//   npm run gen:activities:check    exit 1 if the module drifted
//
// Needs the Godot binary (env GODOT overrides the default path) and a
// core-loop checkout next to this repo (env CORE_LOOP overrides).
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const designLabRoot = resolve(fileURLToPath(import.meta.url), '../..');
const coreLoopRoot = process.env.CORE_LOOP ?? resolve(designLabRoot, '../lifelines-core-loop');
const godotBin = process.env.GODOT ?? '/Applications/Godot.app/Contents/MacOS/Godot';
const modulePath = join(designLabRoot, 'src/content/generated/activityCatalog.ts');
const checkMode = process.argv.includes('--check');

const workDir = mkdtempSync(join(tmpdir(), 'activity-catalog-'));
const jsonPath = join(workDir, 'activity-catalog.json');
try {
  execFileSync(
    godotBin,
    ['--headless', '--script', 'scripts/tools/export_activity_catalog.gd', '--', jsonPath],
    { cwd: coreLoopRoot, stdio: ['ignore', 'ignore', 'inherit'] },
  );
  const payload = JSON.parse(readFileSync(jsonPath, 'utf8'));
  const generated = await prettier.format(renderModule(payload), {
    ...(await prettier.resolveConfig(modulePath)),
    filepath: modulePath,
  });
  if (checkMode) {
    let committed = '';
    try {
      committed = readFileSync(modulePath, 'utf8');
    } catch {
      // missing file counts as drift
    }
    if (committed !== generated) {
      console.error(
        `activity catalog drift: ${modulePath} does not match core-loop ActivityIds.\n` +
          'Run: npm run gen:activities',
      );
      process.exit(1);
    }
    console.log(`activity catalog in sync (${payload.count} activities)`);
  } else {
    writeFileSync(modulePath, generated);
    console.log(`wrote ${payload.count} activities to ${modulePath}`);
  }
} finally {
  rmSync(workDir, { recursive: true, force: true });
}

function renderModule(payload) {
  const rows = payload.activities
    .map((a) => `  { id: '${a.id}', name: ${JSON.stringify(a.name)}, constName: '${a.const}' },`)
    .join('\n');
  return `// GENERATED by scripts/sync-activity-catalog.mjs (SB-110). Do not edit.
// Source of truth: core-loop ${payload.source} via
// scripts/tools/export_activity_catalog.gd. Re-sync: npm run gen:activities

/** One engine activity: wire id (stage grammar \`do <id>\`), display name
 * (the sim's Activity node name), and its ActivityIds constant. */
export interface ActivityEntry {
  id: string;
  name: string;
  constName: string;
}

export const ACTIVITY_CATALOG: readonly ActivityEntry[] = [
${rows}
];

/** Wire ids the stage grammar may reference with \`do\`. */
export const ACTIVITY_IDS: ReadonlySet<string> = new Set(
  ACTIVITY_CATALOG.map((entry) => entry.id),
);

/** Display name for a wire id, or null for an unknown id. */
export const activityName = (id: string): string | null =>
  ACTIVITY_CATALOG.find((entry) => entry.id === id)?.name ?? null;
`;
}
